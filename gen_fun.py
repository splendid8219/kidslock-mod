import json
import random

random.seed(20261107)

questions = []


def add(q, a, distractors):
    """distractors: 候选错误答案池（>=3，且不含 a），自动抽 3 个"""
    pool = [x for x in distractors if x != a]
    random.shuffle(pool)
    d = pool[:3]
    if len(d) < 3:  # 池不够时补占位（极少触发）
        while len(d) < 3:
            d.append("以上都不对")
    questions.append({"q": q, "a": a, "d": d})


def add_hand(q, a, d):
    """手工题：直接给 3 个干扰项"""
    questions.append({"q": q, "a": a, "d": d})


